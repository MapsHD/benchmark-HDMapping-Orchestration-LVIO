#!/usr/bin/env python3
"""Step 6: how much of each sequence's ground truth every exported trajectory covers.

The LIO benchmark's Step 6 reports the duration ratio and the node-count ratio. The node ratio
depends on the output rate (Coco-LIC 100 Hz, LVI-SAM 5 Hz), so here the coverage is measured on
the ground-truth time line instead. Per run (Step 4 trajectory against the ground-truth stamps):

  start_delay_s       first trajectory pose minus first ground-truth pose
  end_shortfall_s     last ground-truth pose minus last trajectory pose (> 0: the trajectory stops early)
  covered_fraction    ground-truth stamps that lie inside the trajectory and not in one of its own
                      gaps longer than --max-gap (the stamps Step 5 can evaluate)
  longest_gap_s       longest interval between two trajectory poses
  rate_hz             median output rate
  duration_ratio      trajectory duration / ground-truth duration (LIO's "metric 1")

Writes results/<seq>/evaluation/overlap/<id>.json and rebuilds results/evaluation/overlap_summary.{csv,md,tex}
from every such file on disk. Needs numpy (the lvio-eval image).
"""

import argparse
import csv
import json
import sys
from pathlib import Path

# common/lvio_py, on PYTHONPATH (overlap.sh mounts it)
import lvio_ground_truth
from lvio_results import missing_reason, trajectory_path
from lvio_trajectory import NS, TrajectoryError, coverage, read_tum

FIELDS = ['sequence', 'algorithm', 'status', 'reason', 'covered_fraction', 'start_delay_s', 'end_shortfall_s',
          'longest_gap_s', 'rate_hz', 'poses', 'duration_ratio', 'gt_poses', 'gt_poses_covered']


def log(msg):
    print(f'[overlap] {msg}', flush=True)


def overlap_run(results, seq, algo, gt_t, max_gap):
    path = trajectory_path(results, seq, algo)
    if not path.is_file():
        return {'status': 'missing', 'reason': missing_reason(results, seq, algo)}
    t, _, _ = read_tum(path)
    if len(t) < 2:
        raise TrajectoryError(f'{path} has {len(t)} pose(s)')
    doc = {'status': 'ok', 'reason': '', **coverage(t, gt_t, int(max_gap * NS))}
    doc['duration_ratio'] = round((int(t[-1]) - int(t[0])) / (int(gt_t[-1]) - int(gt_t[0])), 4)
    doc['max_gap_s'] = max_gap
    return doc


def fmt(row, key, spec):
    if row['status'] == 'n/a':
        return 'n/a'
    value = row.get(key)
    return '–' if row['status'] != 'ok' or value in (None, '') else spec.format(value)


def write_summary(results, seqs, algos, max_gap):
    rows = []
    for seq in seqs:
        for algo in algos:
            path = results / seq / 'evaluation' / 'overlap' / f'{algo}.json'
            doc = json.loads(path.read_text()) if path.is_file() else {'status': 'not evaluated',
                                                                      'reason': 'Step 6 not run for it'}
            rows.append({'sequence': seq, 'algorithm': algo, **{k: doc.get(k, '') for k in FIELDS[2:]}})
    out = results / 'evaluation'
    out.mkdir(parents=True, exist_ok=True)
    with open(out / 'overlap_summary.csv', 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)

    cols = [('Covered [%]', 'covered_fraction', '{:.1%}'), ('Start delay [s]', 'start_delay_s', '{:+.2f}'),
            ('Ends early by [s]', 'end_shortfall_s', '{:+.2f}'), ('Longest gap [s]', 'longest_gap_s', '{:.2f}'),
            ('Rate [Hz]', 'rate_hz', '{:.1f}'), ('Poses', 'poses', '{}'), ('Duration ratio [%]', 'duration_ratio', '{:.1%}')]
    md = ['# Ground-truth coverage (Step 6)', '',
          f'Coverage = share of the ground-truth stamps inside the trajectory and not in one of its own gaps '
          f'longer than {max_gap} s, i.e. the stamps Step 5 evaluates. "Ends early by" > 0 means the trajectory '
          f'stops before the ground truth does. The duration ratio is the LIO benchmark\'s "metric 1".', '']
    for seq in seqs:
        md += [f'## {seq}', '', '| Algorithm | ' + ' | '.join(c[0] for c in cols) + ' |',
               '| --- |' + ' ---: |' * len(cols)]
        for r in rows:
            if r['sequence'] == seq:
                cells = [fmt(r, key, spec) for _, key, spec in cols]
                note = '' if r['status'] == 'ok' else f" ({r['status']}: {r['reason']})"
                md.append(f"| {r['algorithm']}{note} | " + ' | '.join(cells) + ' |')
        md.append('')
    (out / 'overlap_summary.md').write_text('\n'.join(md))

    tex = ['% Generated by steps/6_overlap/overlap.py', '\\begin{table}[]', '\\centering',
           '\\begin{tabular}{l' + 'r' * len(seqs) + '}', '\\rowcolor[HTML]{C0C0C0}',
           'Algorithm & ' + ' & '.join(seqs) + ' \\\\']
    for algo in algos:
        by = {r['sequence']: r for r in rows if r['algorithm'] == algo}
        tex.append(f'{algo} & ' + ' & '.join(fmt(by[s], 'covered_fraction', '{:.1%}').replace('%', '\\%')
                                              .replace('–', '-') for s in seqs) + ' \\\\')
    tex += ['\\end{tabular}', '\\caption{Share of the ground-truth stamps covered by each trajectory.}',
            '\\label{tab:lvio_overlap}', '\\end{table}', '']
    (out / 'overlap_summary.tex').write_text('\n'.join(tex))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--results', type=Path, required=True)
    parser.add_argument('--datasets', type=Path, required=True, help='the datasets/ folder (ground truth inside)')
    parser.add_argument('--calibration-dir', type=Path, required=True, help='folder with <dataset>_calibration.yaml')
    parser.add_argument('--sequences', nargs='+', required=True, help='every sequence as id=DATASET, in order')
    parser.add_argument('--algos', nargs='+', required=True, help='every algorithm as id=DATASET[,DATASET...], in order')
    parser.add_argument('--select-sequences', nargs='*', default=None)
    parser.add_argument('--select-algos', nargs='*', default=None)
    parser.add_argument('--max-gap', type=float, default=0.5)
    args = parser.parse_args()

    seqs = [tuple(a.split('=', 1)) for a in args.sequences]
    supported = {a: set(ds.split(',')) for a, ds in (x.split('=', 1) for x in args.algos)}
    algos = list(supported)
    sel_seqs = set(args.select_sequences or [s for s, _ in seqs])
    sel_algos = set(args.select_algos or algos)
    failures = 0
    for seq, dataset in seqs:
        if seq not in sel_seqs:
            continue
        gt_t = lvio_ground_truth.load(args.datasets, dataset, seq, args.calibration_dir)['t']
        out = args.results / seq / 'evaluation' / 'overlap'
        out.mkdir(parents=True, exist_ok=True)
        log(f'{seq} ({dataset}): ground truth {len(gt_t)} poses, {(gt_t[-1] - gt_t[0]) / NS:.1f} s')
        for algo in algos:
            if algo not in sel_algos:
                continue
            if dataset not in supported[algo]:
                doc = {'status': 'n/a', 'reason': f'not supported on {dataset} (algorithms.conf)'}
            else:
                try:
                    doc = overlap_run(args.results, seq, algo, gt_t, args.max_gap)
                except (TrajectoryError, OSError, ValueError) as err:
                    doc = {'status': 'failed', 'reason': str(err)}
                    failures += 1
            if doc['status'] == 'ok':
                log(f"  {algo:11s} covered {doc['covered_fraction']:.1%}, start {doc['start_delay_s']:+.2f} s, "
                    f"ends early by {doc['end_shortfall_s']:+.2f} s, longest gap {doc['longest_gap_s']:.2f} s, "
                    f"{doc['rate_hz']} Hz")
            else:
                log(f"  {algo:11s} {doc['status']}: {doc['reason']}")
            (out / f'{algo}.json').write_text(json.dumps({'sequence': seq, 'dataset': dataset, 'algorithm': algo, **doc},
                                                         indent=1) + '\n')
    write_summary(args.results, [s for s, _ in seqs], algos, args.max_gap)
    log(f"summary: {args.results / 'evaluation' / 'overlap_summary.md'}")
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
